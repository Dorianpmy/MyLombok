import type { TravelPlace } from "./destination-types";

const verifiedAt = "2026-08-13";

function navigation(latitude: number, longitude: number) {
  return `https://www.google.com/maps/search/?api=1&query=${latitude},${longitude}`;
}

function osm(latitude: number, longitude: number) {
  return `https://www.openstreetmap.org/?mlat=${latitude}&mlon=${longitude}#map=17/${latitude}/${longitude}`;
}

type KualaLumpurPlaceInput = Omit<TravelPlace, "id" | "destinationId" | "navigationUrl" | "lastVerifiedAt" | "verificationStatus">;

function place(input: KualaLumpurPlaceInput): TravelPlace {
  return {
    ...input,
    id: `kuala-lumpur:${input.slug}`,
    destinationId: "kuala-lumpur",
    navigationUrl: navigation(input.coordinates.latitude, input.coordinates.longitude),
    sourceUrls: Array.from(new Set([...input.sourceUrls, osm(input.coordinates.latitude, input.coordinates.longitude)])),
    lastVerifiedAt: verifiedAt,
    verificationStatus: "verified" as const,
  };
}

